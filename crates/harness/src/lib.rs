    #[test]
    fn everything_in_the_environment_has_an_installer_and_what_signs_in_says_how() {
        let registry = Registry::public();
        let all = registry.all();
        assert_eq!(
            all.iter()
                .map(|setup| &setup.id)
                .collect::<HashSet<_>>()
                .len(),
            all.len()
        );
        for setup in &all {
            assert!(
                !setup.install.is_empty() && !setup.command.is_empty(),
                "{}",
                setup.id
            );
            if setup.sign_in.is_some() {
                assert!(
                    setup.sign_in_hint.is_some(),
                    "{} says what signing in asks",
                    setup.id
                );
            }
        }
        let gh = registry.get("gh").unwrap();
        assert!(!gh.is_agent() && registry.agent("gh").is_none());
        let sign_in = gh.sign_in.as_deref().unwrap();
        assert!(sign_in.contains("</dev/null") && sign_in.ends_with("gh auth setup-git"));
        assert_eq!(all.last().unwrap().id, "gh");
        assert_eq!(
            all.iter()
                .map(|setup| setup.id.as_str())
                .collect::<Vec<_>>(),
            [
                "claude",
                "codex",
                "opencode",
                "pi",
                "antigravity",
                "muse",
                "hermes",
                "deepseek",
                "fx",
                "gh"
            ]
        );
    }

    #[test]
    fn a_run_line_names_its_agent_and_quotes_the_prompt() {
        let registry = Registry::public();
        let claude = registry.get("claude").unwrap();
        assert_eq!(run_line(claude, "hello"), "claude -p 'hello'");
        assert_eq!(
            run_line(registry.get("codex").unwrap(), "hi"),
            "codex exec 'hi'"
        );
        assert_eq!(
            run_line(registry.get("opencode").unwrap(), "hi"),
            "opencode run 'hi'"
        );
        assert_eq!(run_line(registry.get("pi").unwrap(), "hi"), "pi 'hi'");
        let bare = Setup {
            id: "x".into(),
            label: "X".into(),
            command: "x".into(),
            install: "true".into(),
            ..Setup::default()
        };
        assert_eq!(run_line(&bare, "hi"), "x 'hi'");
        assert_eq!(
            run_line(registry.get("hermes").unwrap(), "hi"),
            "hermes chat -q 'hi'"
        );
        assert!(run_line(claude, "'; rm -rf ~; echo '").starts_with("claude -p '"));
        assert_eq!(sh_quote("a'b"), r#"'a'"'"'b'"#);
    }

