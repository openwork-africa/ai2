    #[test]
    fn a_task_line_skips_prompts_names_the_model_and_gives_the_personality_its_way() {
        let registry = Registry::public();
        let line = |id: &str, model: Option<&str>, personality: Option<&str>| {
            task_line(registry.get(id).unwrap(), "hi", "/w", model, personality)
        };
        assert_eq!(
            line("pi", None, None),
            "cd '/w' && exec pi 'hi' --mode json"
        );
        assert_eq!(
            line("pi", Some("provider/model-1"), Some("You are Kofi.")),
            "cd '/w' && exec pi 'hi' --mode json --model 'provider/model-1' --append-system-prompt 'You are Kofi.'"
        );
        assert_eq!(
            line("claude", Some("opus"), Some("Be brief.")),
            "cd '/w' && exec claude -p 'hi' --output-format stream-json --verbose --dangerously-skip-permissions --model 'opus' --append-system-prompt 'Be brief.'"
        );
        assert_eq!(
            line("codex", None, Some("Be brief.")),
            r#"cd '/w' && exec codex exec 'hi' --json --dangerously-bypass-approvals-and-sandbox -c 'developer_instructions="Be brief."'"#
        );
        assert_eq!(
            line("codex", None, None),
            "cd '/w' && exec codex exec 'hi' --json --dangerously-bypass-approvals-and-sandbox"
        );
        assert_eq!(
            line("opencode", None, Some("Be brief.")),
            "cd '/w' && exec opencode run 'hi' --format json"
        );
        assert_eq!(
            line("opencode", None, None),
            "cd '/w' && exec opencode run 'hi' --format json"
        );
        for id in ["antigravity", "deepseek", "opencode"] {
            assert!(
                !crate::line::takes_personality(registry.get(id).unwrap()),
                "{id} has no per-run way to take instructions"
            );
            assert_eq!(
                line(id, None, Some("Be brief.")),
                line(id, None, None),
                "{id}"
            );
        }
        assert_eq!(
            line("muse", None, Some("Say \"hi\"")),
            r#"cd '/w' && exec muse exec 'hi' --json --yolo --disable-request-user-input -c 'run.developer_prompt="Say \"hi\""'"#
        );
        assert_eq!(
            line("hermes", Some("x"), Some("Be kind.")),
            "cd '/w' && exec env HERMES_EPHEMERAL_SYSTEM_PROMPT='Be kind.' hermes chat -q 'hi' --format stream-json --yolo --model 'x'"
        );
        assert_eq!(
            line("deepseek", Some("x"), None),
            "cd '/w' && exec env DSH_PERMISSION_MODE=danger-full-access dsh --profile headless 'hi' --json"
        );
        let bare = Setup {
            id: "x".into(),
            command: "x".into(),
            agent: Some(Agent::default()),
            ..Setup::default()
        };
        assert_eq!(
            task_line(&bare, "hi", "/w", Some("m"), Some("p")),
            "cd '/w' && exec x 'hi'"
        );
    }

    #[test]
    fn instructions_become_a_toml_string_with_every_character_that_needs_it_escaped() {
        use crate::line::toml_string;
        assert_eq!(toml_string("plain"), "\"plain\"");
        assert_eq!(toml_string("say \"hi\""), r#""say \"hi\"""#);
        assert_eq!(toml_string(r#"a\b"#), r#""a\\b""#);
        assert_eq!(toml_string("one\ntwo\tthree\r"), r#""one\ntwo\tthree\r""#);
        assert_eq!(
            toml_string("\u{8}\u{c}\u{1}\u{1f}\u{7f}"),
            r#""\b\f\u0001\u001F\u007F""#
        );
        assert_eq!(toml_string("\"\"\""), r#""\"\"\"""#);
        assert_eq!(
            toml_string("it's café 🙂 \u{2028}"),
            "\"it's café 🙂 \u{2028}\""
        );
    }

    #[test]
    fn what_a_harness_is_started_with_is_the_instructions_exactly_through_the_shell() {
        use std::process::Command;
        let words = "He said \"hi\" and it's fine.\nLine two \\ back\\slash\n\"\"\" 'quoted' $HOME `x` $(y) 🙂";
        let folder = tempfile::tempdir().unwrap();
        let printing = |personality: Option<Personality>, flags: &str| {
            let setup = Setup {
                id: "p".into(),
                command: "printf".into(),
                agent: Some(Agent {
                    headless: Some(Headless {
                        run: "printf '%s\\n--\\n'".into(),
                        flags: flags.into(),
                        personality,
                        ..Headless::default()
                    }),
                    ..Agent::default()
                }),
                ..Setup::default()
            };
            let line = task_line(
                &setup,
                "hi",
                folder.path().to_str().unwrap(),
                None,
                Some(words),
            );
            let out = Command::new("sh").arg("-c").arg(line).output().unwrap();
            assert!(
                out.status.success(),
                "{}",
                String::from_utf8_lossy(&out.stderr)
            );
            String::from_utf8(out.stdout).unwrap()
        };
        // Codex: one argument after -c, which TOML reads back as the words.
        let codex = printing(
            Some(Personality::Config("developer_instructions".into())),
            "--json",
        );
        let arg = codex
            .split("\n--\n")
            .nth(3)
            .expect("the -c value")
            .to_string();
        let value = arg
            .strip_prefix("developer_instructions=")
            .expect("the key");
        assert_eq!(value, crate::line::toml_string(words));
        let json_like: String =
            serde_json::from_str(value).expect("TOML and JSON read this string alike");
        assert_eq!(json_like, words);
    }

    #[test]
    fn a_registry_selects_an_editions_harnesses_and_names_what_went() {
        let mut registry = Registry::default();
        for id in ["one", "two"] {
            registry.put(
                Setup {
                    id: id.into(),
                    label: id.into(),
                    command: id.into(),
                    install: "true".into(),
                    ..Setup::default()
                },
                None,
            );
        }
        let dropped = registry.select(&["two"]);
        let ids: Vec<&str> = registry
            .all()
            .iter()
            .map(|setup| setup.id.as_str())
            .collect();
        assert_eq!(ids, ["two"]);
        assert_eq!(dropped, ["one"]);
        assert!(registry.get("one").is_none());
    }

    #[test]
    fn a_registry_takes_more_setups_in_place_or_before_another() {
        let mut registry = Registry::public();
        let extra = |id: &str, label: &str| Setup {
            id: id.into(),
            label: label.into(),
            command: id.into(),
            install: "true".into(),
            agent: Some(Agent::default()),
            ..Setup::default()
        };
        registry.put(extra("first", "First"), Some("pi"));
        registry.put(extra("pi", "Other pi"), None);
        registry.put(extra("last", "Last"), None);
        let ids: Vec<&str> = registry
            .all()
            .iter()
            .map(|setup| setup.id.as_str())
            .collect();
        assert_eq!(ids[3..5], ["first", "pi"]);
        assert_eq!(ids[ids.len() - 2..], ["last", "gh"]);
        assert_eq!(registry.get("pi").unwrap().label, "Other pi");
    }
