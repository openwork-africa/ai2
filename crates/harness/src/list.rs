pub fn npm_global(package: &str, command: &str) -> String {
    format!(
        r#"if command -v npm >/dev/null 2>&1; then npm install -g --prefix "$HOME/.local" {package}; else deno install --global --allow-all --force --root "$HOME/.local" --name {command} npm:{package}; fi"#
    )
}

const NODE_IS_NEW: &str = r#"node -e 'const [a,b]=process.versions.node.split(".").map(Number); process.exit(a>22||(a===22&&b>=19)?0:1)'"#;

pub fn node_install() -> String {
    [
        &format!("if ! {{ command -v node >/dev/null 2>&1 && {NODE_IS_NEW}; }}; then"),
        "  case $(uname -s) in Darwin) p=darwin;; *) p=linux;; esac",
        r#"  case $(uname -m) in x86_64|amd64) a=x64;; aarch64|arm64) a=arm64;; *) echo "No Node.js build for $(uname -m)"; exit 1;; esac"#,
        r#"  base=https://nodejs.org/dist/latest-v22.x; t=$(mktemp -d); dir="$HOME/.local/share/pi-node""#,
        r#"  curl -fsSL "$base/SHASUMS256.txt" -o "$t/SHASUMS256.txt""#,
        r#"  f=$(awk -v s="-$p-$a.tar.gz" 'index($2,"node-v")==1 && substr($2,length($2)-length(s)+1)==s {print $2; exit}' "$t/SHASUMS256.txt")"#,
        r#"  curl -fsSL "$base/$f" -o "$t/$f""#,
        "  sum() { if command -v sha256sum >/dev/null 2>&1; then sha256sum -c -; else shasum -a 256 -c -; fi; }",
        r#"  (cd "$t" && grep " $f$" SHASUMS256.txt | sum)"#,
        r#"  mkdir -p "$dir" "$HOME/.local/bin" && rm -rf "$dir/${f%.tar.gz}" && tar -xzf "$t/$f" -C "$dir" && ln -sfn "$dir/${f%.tar.gz}" "$dir/current""#,
        r#"  for c in node npm npx; do ln -sf "$dir/current/bin/$c" "$HOME/.local/bin/$c"; done"#,
        r#"  rm -rf "$t""#,
        "fi",
    ]
    .join("\n")
}

const PI_PACKAGE: &str = "@earendil-works/pi-coding-agent";
const PI_OLD_PACKAGE: &str = "@mariozechner/pi-coding-agent";

pub fn pi_install() -> String {
    [
        "set -e".to_string(),
        node_install(),
        format!(r#"npm uninstall -g --prefix "$HOME/.local" {PI_OLD_PACKAGE} >/dev/null 2>&1 || true"#),
        r#"if grep -qs "generated by deno install" "$HOME/.local/bin/pi"; then rm -rf "$HOME/.local/bin/pi" "$HOME/.local/bin/.pi"; fi"#.to_string(),
        format!(r#"npm install -g --ignore-scripts --prefix "$HOME/.local" {PI_PACKAGE}"#),
        "pi --version".to_string(),
    ]
    .join("\n")
}

pub fn dsh_install() -> String {
    [
        "set -e".to_string(),
        node_install(),
        r#"if grep -qs "generated by deno install" "$HOME/.local/bin/dsh"; then rm -rf "$HOME/.local/bin/dsh" "$HOME/.local/bin/.dsh"; fi"#.to_string(),
        r#"npm install -g --prefix "$HOME/.local" @deepseek-ai/dsh"#.to_string(),
        "dsh --version".to_string(),
    ]
    .join("\n")
}

fn dsh_sign_in() -> String {
    [
        "printf 'DeepSeek API key: '",
        "read -r key",
        r#"[ -n "$key" ] || { echo "No key given."; exit 1; }"#,
        r#"mkdir -p "$HOME/.dsh"; umask 077; f="$HOME/.dsh/.env""#,
        concat!(
            r#"{ grep -sv '^DEEPSEEK_API_KEY=' "$f" || true; printf 'DEEPSEEK_API_KEY=%s"#,
            "\n",
            r#"' "$key"; } > "$f.new" && mv "$f.new" "$f""#
        ),
        r#"echo "Saved.""#,
    ]
    .join("; ")
}

fn gh_install() -> String {
    [
        "set -e",
        "v=$(curl -fsSLI -o /dev/null -w '%{url_effective}' https://github.com/cli/cli/releases/latest | sed 's#.*/v##')",
        "case $(uname -m) in x86_64|amd64) a=amd64;; aarch64|arm64) a=arm64;; *) a=386;; esac",
        "t=$(mktemp -d)",
        r#"if [ "$(uname -s)" = Darwin ]; then n=gh_${v}_macOS_$a; curl -fsSLo "$t/gh.zip" "https://github.com/cli/cli/releases/download/v$v/$n.zip"; unzip -q "$t/gh.zip" -d "$t""#,
        r#"else n=gh_${v}_linux_$a; curl -fsSL "https://github.com/cli/cli/releases/download/v$v/$n.tar.gz" | tar -xz -C "$t"; fi"#,
        r#"mkdir -p "$HOME/.local/bin""#,
        r#"cp "$t/$n/bin/gh" "$HOME/.local/bin/gh""#,
        r#"rm -rf "$t""#,
        "gh --version",
    ]
    .join("; ")
}

pub fn headless(run: &str, flags: &str) -> Headless {
    Headless {
        run: run.into(),
        flags: flags.into(),
        ..Headless::default()
    }
}

pub fn flag(name: &str) -> Option<Personality> {
    Some(Personality::Flag(name.into()))
}

fn some(text: &str) -> Option<String> {
    Some(text.into())
}

pub fn agent(
    id: &str,
    label: &str,
    command: &str,
    install: String,
    models: Vec<ModelChoice>,
    headless: Headless,
) -> Setup {
    Setup {
        id: id.into(),
        label: label.into(),
        command: command.into(),
        install,
        agent: Some(Agent {
            models,
            headless: Some(headless),
        }),
        ..Setup::default()
    }
}

fn signs_in(setup: Setup, line: &str, hint: &str) -> Setup {
    Setup {
        sign_in: some(line),
        sign_in_hint: some(hint),
        ..setup
    }
}

fn logo(setup: Setup, file: &str) -> Setup {
    Setup {
        logo: some(file),
        ..setup
    }
}

fn muse_personality(personality: &str) -> String {
    let given = serde_json::to_string(personality).unwrap_or_default();
    format!("-c {}", sh_quote(&format!("run.developer_prompt={given}")))
}

